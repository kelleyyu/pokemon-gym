  /** 根据当前状态生成"贴心提醒"类台词 */
  function contextTips(ctx) {
    const t = [];
    if (ctx.homeworkLeft > 0) t.push('还有 ' + ctx.homeworkLeft + ' 项作业没打勾哦，我们一起消灭它们！');
    if (ctx.homeworkLeft === 0 && ctx.homeworkTotal > 0) t.push('作业全部完成啦！你今天超级棒，皮卡皮卡！');
    if (!ctx.readingDone) t.push('今天还没读书哦，读 20 分钟就有 30 金币呢～');
    if (!ctx.sportsDone) t.push('动一动嘛！跳绳 10 分钟，我在旁边给你数！');
    if (ctx.quizLeft > 0) t.push('闯关还剩 ' + ctx.quizLeft + ' 次机会，去拿满分好不好？');
    if (ctx.canFeed) t.push('我的肚子在叫…今天还没喂我呢（可怜巴巴地看着你）');
    if (ctx.badgeReady > 0) t.push('有 ' + ctx.badgeReady + ' 枚徽章可以领奖啦，快去领！');
    if (ctx.nearEvolve) t.push('我感觉身体在发光…是不是快要进化了？！');
    return t;
  }

  /** 抽一句台词；riddle 返回对象 */
  function next(ctx) {
    const pool = [];
    const tips = ctx ? contextTips(ctx) : [];
    tips.forEach((x) => pool.push({ type: 'tip', text: x }));
    tips.forEach((x) => pool.push({ type: 'tip', text: x })); // 提醒权重更高
    cute.forEach((x) => pool.push({ type: 'cute', text: x }));
    boost.forEach((x) => pool.push({ type: 'boost', text: x }));
    jokes.forEach((x) => pool.push({ type: 'joke', text: x }));
    riddles.forEach((x) => pool.push({ type: 'riddle', text: '脑筋急转弯：' + x.q, answer: x.a }));
    return pool[Math.floor(Math.random() * pool.length)];
  }

  return { cute, jokes, riddles, boost, next, contextTips };
